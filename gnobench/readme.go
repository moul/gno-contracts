// The README carries a generated region so the front page is never out of date
// with the data. Everything above and below the markers is prose and is never
// touched; everything between them is rewritten by `make report`.
//
// The markers follow the convention the repository root README already uses.
const (
	readmeBegin = "<!-- BEGIN RESULTS (generated by `make report`; do not edit by hand) -->"
	readmeEnd   = "<!-- END RESULTS -->"
)

// updateREADME rewrites the generated region from every suite's result files.
// It reads what is on disk rather than what a run just measured, so the region
// is correct even when only one suite was re-run.
func updateREADME(root string) error {
	path := filepath.Join(root, "README.md")
	cur, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	body := string(cur)
	i := strings.Index(body, readmeBegin)
	j := strings.Index(body, readmeEnd)
	if i < 0 || j < 0 || j < i {
		return fmt.Errorf("%s: the generated region markers are missing or out of order; "+
			"restore %q ... %q", path, readmeBegin, readmeEnd)
	}

	var b strings.Builder
	b.WriteString(readmeBegin + "\n\n")
	b.WriteString("_Every figure below is read out of `results/`. Do not edit: run `make report`._\n")

	names := suiteNames()
	sort.Strings(names)
	wrote := 0
	for _, name := range names {
		s := suites[name]
		files, err := LoadAll(root, name)
		if err != nil {
			return err
		}
		if len(files) == 0 {
			continue
		}
		wrote++
		b.WriteString("\n" + suiteSummary(root, s, files))
	}
	if wrote == 0 {
		b.WriteString("\nNothing measured yet. Run `make bench`.\n")
	}
	b.WriteString("\n" + readmeEnd)

	out := body[:i] + b.String() + body[j+len(readmeEnd):]
	if out == body {
		return nil
	}
	return os.WriteFile(path, []byte(out), 0o644)
}

func suiteSummary(root string, s *Suite, files []*File) string {
	var b strings.Builder
	fmt.Fprintf(&b, "### `%s`: %s\n\n", s.Name, s.Title)

	// Provenance first. A number without the machine and the gno revision
	// that produced it is not reproducible.
	for _, f := range files {
		rows := 0
		for _, r := range f.Rows {
			if r.Skip == "" && r.Err == "" {
				rows++
			}
		}
		fmt.Fprintf(&b, "%s **%s** measured rows on `%s` (%s), Go %s, gno `%s`, last updated %s.\n",
			bullet(), addCommas(itoa(rows)), f.Env.ID, f.Env.Short(),
			strings.TrimPrefix(f.Env.GoVer, "go"), f.Env.GnoShort(), shortDate(f.UpdatedAt))
	}

	v := newView(files[0])
	for _, line := range headlines(s, v) {
		fmt.Fprintf(&b, "%s %s\n", bullet(), line)
	}

	// The charts, each one a link into the section of the full report that
	// explains it.
	refs, err := writeCharts(root, s, files)
	if err == nil {
		for _, r := range refs {
			b.WriteString("\n" + picture(r) + "\n")
		}
	}

	if t := cheapestTable(s, v); t != "" {
		b.WriteString("\n" + t)
	}

	fmt.Fprintf(&b, "\n[Full report](reports/%s.md) `·` [Dashboard, filterable](reports/%s.html) `·` [Raw rows](results/%s/)\n",
		s.Name, s.Name, s.Name)
	return b.String()
}

func bullet() string { return "-" }

func max64(a, b int64) int64 {
	if a > b {
		return a
	}
	return b
}

// ratio formats a multiple: one decimal while it is small enough to matter,
// thousands separators once it is not.
func ratio(f float64) string {
	if f < 100 {
		return fmt.Sprintf("%.1f", f)
	}
	return addCommas(fmt.Sprintf("%.0f", f))
}

// picture is the two-theme image GitHub needs: one chart tuned for a light
// background is unreadable on a dark one, and half of readers use each.
func picture(r chartRef) string {
	return fmt.Sprintf(`<a href="reports/%s.md#%s">
  <picture>
    <source media="(prefers-color-scheme: dark)" srcset="reports/%s-%s-dark.svg">
    <img alt="%s" src="reports/%s-%s-light.svg" width="860">
  </picture>
</a>`, r.Suite, r.Anchor, r.Suite, r.Slug, esc(r.Title), r.Suite, r.Slug)
}

// headlines are the two or three sentences worth putting on a front page, each
// computed from the rows so none of them can drift from the data.
func headlines(s *Suite, v view) []string {
	sizes := v.sizes()
	if len(sizes) == 0 {
		return nil
	}
	big := sizes[len(sizes)-1]
	var out []string

	if best, worst, ok := extremes(s, v, "kv", "str", "cold", "tx_read", big); ok {
		out = append(out, fmt.Sprintf(
			"One cold read against %s entries: **`%s` at %s gas**, against `%s` at %s. A **%sx** spread.",
			addCommas(itoa(big)), best.Label, fmtN(best.Value), worst.Label, fmtN(worst.Value),
			ratio(worst.Value/best.Value)))
	}
	// Keyed containers only: comparing a positional list against a tree on
	// bytes per entry is not a choice anyone is making.
	if bars := collectBytes(s, v, "str", big, "kv"); len(bars) >= 2 {
		lo, hi := bars[0], bars[len(bars)-1]
		out = append(out, fmt.Sprintf(
			"Storage per entry, keyed containers: **`%s` at %s bytes**, against `%s` at %s. At 100k entries that is %s GNOT of deposit against %s.",
			lo.Label, fmtN(lo.Value), hi.Label, fmtN(hi.Value),
			fmtN(lo.Value*100000*100/1e6), fmtN(hi.Value*100000*100/1e6)))
	}
	// The warm/cold gap, which is the reason this tool exists.
	if w, okw := v.get("builtin map[string]any", "str", "warm", "get_hit", big); okw {
		if c, okc := v.get("builtin map[string]any", "str", "cold", "tx_read", big); okc && w.Ops > 0 {
			warm := float64(w.DGas) / float64(w.Ops)
			cold := float64(c.DGas) / float64(max(c.Ops, 1))
			out = append(out, fmt.Sprintf(
				"A `builtin map` read looks like %s gas warm and costs **%s gas** in a real transaction, **%sx** more, because the whole map is one persisted object and the first touch loads all of it.",
				fmtN(warm), fmtN(cold), ratio(cold/warm)))
		}
	}
	if s.Name == "wiring" {
		var lo, hi *Row
		var loName, hiName string
		for _, c := range wiringCandidates {
			r, ok := v.get(c.Name, "str", "cold", shapePerTx, big)
			if !ok || r.KVSetBytes == 0 {
				continue
			}
			rr := r
			if lo == nil || rr.KVSetBytes < lo.KVSetBytes {
				lo, loName = &rr, c.Name
			}
			if hi == nil || rr.KVSetBytes > hi.KVSetBytes {
				hi, hiName = &rr, c.Name
			}
		}
		if lo != nil && hi != nil && lo.KVSetBytes > 0 {
			one, _ := v.get(hiName, "str", "cold", shapeOneTx, big)
			out = append(out, fmt.Sprintf(
				"%s writes arriving one transaction at a time, all ending at the same state and charged the same deposit: **`%s` makes the node write %s MB**, against `%s` at %s MB. The worst of them writes **%sx** what the same writes cost batched into one transaction.",
				addCommas(itoa(big)), hiName, fmtN(float64(hi.KVSetBytes)/1e6),
				loName, fmtN(float64(lo.KVSetBytes)/1e6),
				ratio(float64(hi.KVSetBytes)/float64(max64(one.KVSetBytes, 1)))))
		}
		return out
	}
	if best, worst, ok := extremes(s, v, "digest", "str", "warm", "x64", big); ok {
		out = append(out, fmt.Sprintf(
			"On %s %s-byte input: **`%s` at %s gas per call**, against `%s` at %s. A **%sx** spread, and it tracks native against interpreted, not algorithm against algorithm.",
			article(big), addCommas(itoa(big)), best.Label, fmtN(best.Value), worst.Label, fmtN(worst.Value),
			ratio(worst.Value/best.Value)))
	}
	return out
}

func extremes(s *Suite, v view, group, value, mode, workload string, n int) (bar, bar, bool) {
	bars := collect(s, v, group, value, mode, workload, n, "")
	if len(bars) < 2 || bars[0].Value <= 0 {
		return bar{}, bar{}, false
	}
	return bars[0], bars[len(bars)-1], true
}

// cheapestTable is the answer in one table: who wins at each size, and where
// the winner changes.
func cheapestTable(s *Suite, v view) string {
	var ops []Workload
	for _, w := range s.Workloads {
		if w.Light && w.Baseline != "" && w.Group == "kv" {
			ops = append(ops, w)
		}
	}
	if len(ops) == 0 {
		return ""
	}
	sizes := v.sizes()
	var body strings.Builder
	rows := 0
	for _, w := range ops {
		var cells []string
		prev, cross := "", ""
		for _, n := range sizes {
			bars := collect(s, v, "kv", "str", w.mode(), w.Name, n, "")
			if len(bars) == 0 {
				cells = append(cells, "")
				continue
			}
			cells = append(cells, fmt.Sprintf("`%s`<br>%s", bars[0].Label, fmtN(bars[0].Value)))
			if prev != "" && prev != bars[0].Label && cross == "" {
				cross = "before " + addCommas(itoa(n))
			}
			prev = bars[0].Label
		}
		rows++
		fmt.Fprintf(&body, "| %s | %s | %s |\n", w.Name, strings.Join(cells, " | "), cross)
	}
	if rows == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString("**Cheapest per size**, one cold transaction, one operation, gas:\n\n| operation |")
	for _, n := range sizes {
		fmt.Fprintf(&b, " n = %s |", addCommas(itoa(n)))
	}
	b.WriteString(" changes hands |\n|---|")
	for range sizes {
		b.WriteString("---|")
	}
	b.WriteString("---|\n")
	b.WriteString(body.String())
	return b.String()
}
